"""Aggregate Exp 7 and Exp 8 runs (mean +/- std over repeats), apply the Exp 8 target,
and draw charts. Usage: python experiments/summarize.py
Outputs: experiments/results/summary.md, exp7_summary.csv, exp8_summary.csv, docs/screenshots/*.png
"""
import json
from pathlib import Path
import statistics as st

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
SHOTS = HERE.parent / "docs" / "screenshots"
METRICS = ["cpu_avg_pct", "cpu_peak_pct", "mem_peak_mib", "cpu_util_of_limit_pct", "mem_util_of_limit_pct",
           "throughput_rps", "latency_ms_p50", "latency_ms_p95", "errors",
           "est_usd_per_hour", "est_usd_per_million_predictions"]


def load(exp):
    return [json.loads(line) for line in (RES / exp / "runs.jsonl").read_text().splitlines()]


def aggregate(runs, order):
    rows = []
    for cfg in order:
        rs = [r for r in runs if r["config"] == cfg]
        row = {"config": cfg, "cpus": rs[0]["cpus"], "memory": rs[0]["memory"], "repeats": len(rs),
               "all_ok": all(r["status"] == "OK" for r in rs), "oom": any(r["oom_killed"] for r in rs)}
        for m in METRICS:
            vals = [r[m] for r in rs]
            row[m] = round(st.mean(vals), 4 if "usd" in m else 1)
            row[m + "_sd"] = round(st.stdev(vals), 4 if "usd" in m else 1) if len(vals) > 1 else 0
        rows.append(row)
    return rows


def md_table(rows, cols):
    head = "| " + " | ".join(c for c, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(f(r) for _, f in cols) + " |\n" for r in rows)


def pm(m):
    return lambda r: f"{r[m]} ± {r[m + '_sd']}"


def write_csv(rows, path):
    keys = list(rows[0])
    path.write_text(",".join(keys) + "\n" + "".join(",".join(str(r[k]) for k in keys) + "\n" for r in rows))


def main():
    e7 = aggregate(load("exp7"), ["over-provisioned", "right-sized"])
    cfg8 = json.loads((HERE / "exp8_configs.json").read_text())
    e8 = aggregate(load("exp8"), [c["name"] for c in cfg8["configs"]])
    tgt = cfg8["performance_target"]
    for r in e8:
        r["meets_target"] = (r["all_ok"] and not r["oom"] and r["errors"] <= tgt["max_errors"]
                             and r["latency_ms_p95"] <= tgt["max_p95_latency_ms"]
                             and r["throughput_rps"] >= tgt.get("min_throughput_rps", 0))
    passing = [r for r in e8 if r["meets_target"]]
    best = min(passing, key=lambda r: r["est_usd_per_million_predictions"]) if passing else None

    o, s = e7
    change = {k: round((s[k] - o[k]) / o[k] * 100, 1) for k in
              ("throughput_rps", "latency_ms_p50", "latency_ms_p95", "est_usd_per_hour", "est_usd_per_million_predictions")}
    write_csv(e7, RES / "exp7_summary.csv")
    write_csv(e8, RES / "exp8_summary.csv")

    cols = [("Config", lambda r: f"{r['config']} ({r['cpus']} vCPU, {r['memory']})"),
            ("CPU peak % of 1 core", pm("cpu_peak_pct")), ("CPU used % of limit", pm("cpu_util_of_limit_pct")),
            ("Mem peak MiB", pm("mem_peak_mib")), ("Mem used % of limit", pm("mem_util_of_limit_pct")),
            ("Throughput req/s", pm("throughput_rps")), ("p50 ms", pm("latency_ms_p50")),
            ("p95 ms", pm("latency_ms_p95")), ("Errors", lambda r: str(int(r["errors"]))),
            ("Est. USD/hour", lambda r: f"{r['est_usd_per_hour']:.4f}"),
            ("Est. USD per 1M predictions", lambda r: f"{r['est_usd_per_million_predictions']:.4f}")]
    out = ["# Experiment 7 & 8 results (generated by experiments/summarize.py)\n",
           "HeatGuard v2 backend (ayushiranjan27/heatguard:2.0, 7-day forecast per request). "
           "Workload (identical for every run): 15000 POST /predict requests built from real IMD 2024 windows, "
           "20 concurrent clients, 100 warm-up requests, fixed seed. Values are mean ± std over 3 repeats. "
           "Containers with Docker CPU/memory limits on an Apple M2 laptop (Docker Desktop VM: 8 CPUs, 3.8 GiB) "
           "emulate cloud instance sizes.\n",
           "**Costs are ESTIMATES, not actual charges**: AWS Fargate on-demand Linux/ARM, ap-south-1 (Mumbai): "
           "USD 0.02383 per vCPU-hour + USD 0.00261 per GB-hour (AWS public price list, published 2026-09-11). "
           "Cost per 1M predictions = hourly cost / (throughput × 3600) × 10^6.\n",
           "## Experiment 7: right-sizing\n",
           md_table(e7, cols),
           f"\nChange after right-sizing: throughput {change['throughput_rps']}%, p50 {change['latency_ms_p50']}%, "
           f"p95 {change['latency_ms_p95']}%, hourly cost {change['est_usd_per_hour']}%, "
           f"cost per 1M predictions {change['est_usd_per_million_predictions']}%.\n",
           "## Experiment 8: instance-size comparison\n",
           f"Target (fixed before running Exp 8): throughput ≥ {tgt['min_throughput_rps']} req/s, p95 ≤ {tgt['max_p95_latency_ms']} ms, "
           f"errors ≤ {tgt['max_errors']}, no OOM kill. Rule: {cfg8['target_rule']}\n",
           md_table(e8, cols + [("Meets target", lambda r: "yes" if r["meets_target"] else "no")]),
           f"\n**Most cost-efficient config meeting the target: {best['config'] if best else 'none'}**"
           + (f" (USD {best['est_usd_per_million_predictions']:.4f} per 1M predictions).\n" if best else ".\n")]
    (RES / "summary.md").write_text("\n".join(out))
    print("\n".join(out))

    SHOTS.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(1, 3, figsize=(13, 3.8))
    for a, (m, label) in zip(ax, [("cpu_util_of_limit_pct", "CPU used (% of limit)"),
                                  ("mem_util_of_limit_pct", "Memory used (% of limit)"),
                                  ("est_usd_per_hour", "Est. USD per hour")]):
        a.bar([f"{r['config']}\n{r['cpus']} vCPU / {r['memory']}" for r in e7], [r[m] for r in e7],
              yerr=[r[m + "_sd"] for r in e7], color=["#b0b0b0", "#b4441c"], capsize=4)
        a.set_title(label)
    fig.suptitle("Exp 7: HeatGuard v2 API before vs after right-sizing (same workload, 3 repeats)")
    fig.tight_layout()
    fig.savefig(SHOTS / "exp7_rightsizing_chart.png", dpi=130)

    fig, ax = plt.subplots(1, 3, figsize=(13, 3.8))
    labels = [f"{r['config']}\n{r['cpus']} vCPU / {r['memory']}" for r in e8]
    colors = ["#b4441c" if best and r["config"] == best["config"] else "#8a8a8a" for r in e8]
    for a, (m, label) in zip(ax, [("throughput_rps", "Throughput (req/s)"), ("latency_ms_p95", "p95 latency (ms)"),
                                  ("est_usd_per_million_predictions", "Est. USD per 1M predictions")]):
        a.bar(labels, [r[m] for r in e8], yerr=[r[m + "_sd"] for r in e8], color=colors, capsize=4)
        a.set_title(label)
        if m == "throughput_rps" and tgt.get("min_throughput_rps"):
            a.axhline(tgt["min_throughput_rps"], ls="--", color="black", lw=1)
            a.text(0.02, tgt["min_throughput_rps"] * 1.02, "target (min)", transform=a.get_yaxis_transform())
        if m == "latency_ms_p95":
            a.axhline(tgt["max_p95_latency_ms"], ls="--", color="black", lw=1)
            a.text(0.02, tgt["max_p95_latency_ms"] * 1.02, "target (max)", transform=a.get_yaxis_transform())
    fig.suptitle("Exp 8: HeatGuard v2 API, same workload on three instance sizes (highlighted = cheapest meeting target)")
    fig.tight_layout()
    fig.savefig(SHOTS / "exp8_finops_chart.png", dpi=130)
    print("charts saved")


if __name__ == "__main__":
    main()
